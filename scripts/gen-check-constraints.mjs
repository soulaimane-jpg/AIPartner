#!/usr/bin/env node
/**
 * Generate the CHECK-constraint migration from `src/lib/db/column-domains.ts`.
 *
 * Run: node scripts/gen-check-constraints.mjs > db/migrations/<name>.sql
 *
 * The domains live in TypeScript because that's where the state machines
 * already are; this keeps the database constraint a projection of them
 * rather than a second, hand-maintained list that drifts.
 *
 * Every constraint is added NOT VALID so the ALTER takes only a brief
 * lock and does not scan the table. A separate VALIDATE step (and the
 * pre-flight report above it) is run deliberately, because VALIDATE is
 * what fails if legacy rows hold a value outside the domain.
 */

import { readFileSync } from "node:fs";

const src = readFileSync(
  new URL("../src/lib/db/column-domains.ts", import.meta.url),
  "utf8",
);

// Deliberately parsed rather than imported: this script must run without
// a TS toolchain in CI or a release image.
function listOf(name) {
  const m = src.match(new RegExp(`${name} = \\[([^\\]]*)\\]`, "s"));
  if (!m) throw new Error(`list ${name} not found`);
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

const enums = readFileSync(
  new URL("../src/lib/enums.ts", import.meta.url),
  "utf8",
);
function enumList(name) {
  const m = enums.match(new RegExp(`${name} = \\[([^\\]]*)\\]`, "s"));
  if (!m) throw new Error(`enum ${name} not found`);
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

const uniqSorted = (...lists) => [...new Set(lists.flat())].sort();

const DOMAINS = [
  ["User", "role", enumList("USER_ROLES")],
  ["Company", "kind", enumList("COMPANY_KINDS")],
  ["Company", "verificationStatus", ["PENDING", "APPROVED", "REJECTED"]],
  // `tier` lives on PartnerProfile, not Company.
  ["PartnerProfile", "tier", enumList("PARTNER_TIER_VALUES")],
  ["Lead", "status", enumList("LEAD_STATUSES")],
  ["ProjectBrief", "stage", enumList("BRIEF_STAGES")],
  ["ProjectBrief", "leadState", enumList("LEAD_STATES")],
  ["ProjectBrief", "status", enumList("BRIEF_STATUSES")],
  [
    "Match",
    "status",
    uniqSorted(enumList("MATCH_STATUSES"), listOf("INVITE_MACHINE_STATES")),
  ],
  [
    "Proposal",
    "status",
    uniqSorted(
      enumList("PROPOSAL_STATUSES"),
      listOf("PROPOSAL_MACHINE_STATES"),
    ),
  ],
  ["BriefCollaborator", "role", enumList("COLLABORATOR_ROLES")],
  ["BriefCollaborator", "status", enumList("COLLABORATOR_STATUSES")],
  ["TimerInstance", "timerType", listOf("TIMER_TYPE_VALUES")],
  ["TimerInstance", "status", ["active", "satisfied", "expired", "cancelled"]],
  [
    "Engagement",
    "status",
    ["PENDING_ACCEPTANCE", "ACTIVE", "DELIVERED", "CANCELLED"],
  ],
  [
    "EngagementMilestone",
    "status",
    ["PENDING", "IN_PROGRESS", "COMPLETED", "BLOCKED"],
  ],
  [
    "WorkspaceJoinRequest",
    "status",
    ["PENDING", "APPROVED", "DECLINED", "CANCELLED"],
  ],
  ["RiskRadarReport", "overall", ["info", "warn", "block", "failed"]],
].map(([table, column, values]) => ({
  table,
  column,
  values: [...new Set(values)].sort(),
  constraint: `${table}_${column}_check`,
}));

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;
const out = [];

out.push(`-- Domain constraints for the enum-like TEXT columns.
--
-- GENERATED by scripts/gen-check-constraints.mjs from
-- src/lib/db/column-domains.ts. Do not edit by hand — regenerate.
--
-- Every lifecycle column was bare TEXT with no CHECK, so the state
-- machines were enforced only in application code. Added NOT VALID so the
-- ALTER takes a short lock without scanning; VALIDATE is a separate,
-- deliberate step because it is what surfaces pre-existing bad rows.
--
-- Pre-flight: run scripts/check-domain-violations.sql first. If it
-- returns any row, fix the data before validating.
`);

for (const d of DOMAINS) {
  const values = d.values.map(lit).join(", ");
  out.push(`-- ${d.table}.${d.column}
DO $$
BEGIN
    ALTER TABLE ${JSON.stringify(d.table)}
        ADD CONSTRAINT ${JSON.stringify(d.constraint)}
        CHECK (${JSON.stringify(d.column)} IN (${values})) NOT VALID;
EXCEPTION
    WHEN duplicate_object THEN NULL;
    WHEN undefined_table  THEN NULL;
    WHEN undefined_column THEN NULL;
END $$;
`);
}

out.push(`-- ── Validation ─────────────────────────────────────────────────
-- Separate statements so a failure names the offending table and the
-- rest of the constraints stay in place (NOT VALID still blocks new bad
-- writes, which is the important half).
`);

for (const d of DOMAINS) {
  out.push(`DO $$
BEGIN
    ALTER TABLE ${JSON.stringify(d.table)} VALIDATE CONSTRAINT ${JSON.stringify(d.constraint)};
EXCEPTION
    WHEN undefined_table  THEN NULL;
    WHEN undefined_object THEN NULL;
END $$;
`);
}

// Assert every constraint actually landed. The ADD blocks above swallow
// undefined_table/undefined_column so the migration is safe to run against
// an older schema — but that also means a typo'd table or column name would
// silently produce NO constraint while the migration reported success. This
// turns that into a loud failure. (It caught a real mistake: `tier` lives on
// PartnerProfile, not Company.)
out.push(`-- ── Post-condition ─────────────────────────────────────────────
DO $$
DECLARE
    expected text[] := ARRAY[
${DOMAINS.map((d) => `        '${d.constraint}'`).join(",\n")}
    ];
    name    text;
    missing text[] := '{}';
BEGIN
    FOREACH name IN ARRAY expected LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint
             WHERE conname = name AND contype = 'c'
        ) THEN
            missing := array_append(missing, name);
        END IF;
    END LOOP;

    IF array_length(missing, 1) > 0 THEN
        RAISE EXCEPTION
            'domain constraints missing (bad table/column name?): %',
            array_to_string(missing, ', ');
    END IF;

    RAISE NOTICE 'all % domain constraints present', array_length(expected, 1);
END $$;
`);

process.stdout.write(out.join("\n"));
